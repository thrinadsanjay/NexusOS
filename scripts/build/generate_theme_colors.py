#!/usr/bin/env python3
"""Generate KDE colour files from the central NexusOS design tokens.

Single source of truth: ``branding/design-tokens.json``.

Outputs (committed, so the Debian source package does not need Python at build time):
  * ``desktop/color-schemes/Nexus.colors``      -- KDE colour scheme (kdeglobals format)
  * ``configs/kde/konsole/Nexus.colorscheme``   -- Konsole terminal palette

Run ``--check`` in CI to fail when generated files drift from the tokens.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
TOKENS_FILE = REPO_ROOT / "branding" / "design-tokens.json"
COLORS_OUT = REPO_ROOT / "desktop" / "color-schemes" / "Nexus.colors"
KONSOLE_OUT = REPO_ROOT / "configs" / "kde" / "konsole" / "Nexus.colorscheme"

HEADER = (
    "# Generated by scripts/build/generate_theme_colors.py from branding/design-tokens.json.\n"
    "# Do not edit by hand. SPDX-License-Identifier: GPL-2.0-or-later\n"
)


def rgb(hex_color: str) -> str:
    """Convert ``#RRGGBB`` to KDE's ``R,G,B`` notation."""
    value = hex_color.lstrip("#")
    if len(value) != 6:
        raise ValueError(f"expected #RRGGBB colour, got {hex_color!r}")
    return ",".join(str(int(value[i : i + 2], 16)) for i in (0, 2, 4))


def load_tokens() -> dict[str, str]:
    data = json.loads(TOKENS_FILE.read_text(encoding="utf-8"))
    tokens: dict[str, str] = {**data["color"]}
    for key, value in data["derived"].items():
        if value.startswith("#"):
            tokens[key] = value
    return tokens


def _foregrounds(t: dict[str, str]) -> dict[str, str]:
    return {
        "DecorationFocus": rgb(t["accent-primary"]),
        "DecorationHover": rgb(t["accent-primary-hover"]),
        "ForegroundActive": rgb(t["accent-primary"]),
        "ForegroundInactive": rgb(t["text-secondary"]),
        "ForegroundLink": rgb(t["accent-primary-hover"]),
        "ForegroundNegative": rgb(t["negative"]),
        "ForegroundNeutral": rgb(t["warning"]),
        "ForegroundNormal": rgb(t["text-primary"]),
        "ForegroundPositive": rgb(t["positive"]),
        "ForegroundVisited": rgb(t["accent-secondary"]),
    }


def _section(name: str, values: dict[str, str]) -> str:
    body = "\n".join(f"{key}={values[key]}" for key in sorted(values))
    return f"[{name}]\n{body}\n"


def render_color_scheme(t: dict[str, str]) -> str:
    fg = _foregrounds(t)
    groups: dict[str, tuple[str, str]] = {
        # group: (BackgroundNormal, BackgroundAlternate)
        "Colors:Button": (t["surface-elevated"], t["background-secondary"]),
        "Colors:Complementary": (t["background-primary"], t["background-secondary"]),
        "Colors:Header": (t["surface-elevated"], t["surface"]),
        "Colors:Header][Inactive": (t["surface"], t["surface-elevated"]),
        "Colors:Tooltip": (t["surface-elevated"], t["surface"]),
        "Colors:View": (t["background-primary"], t["surface"]),
        "Colors:Window": (t["surface"], t["surface-elevated"]),
    }
    sections = [
        _section(
            "ColorEffects:Disabled",
            {
                "Color": rgb(t["surface"]),
                "ColorAmount": "0",
                "ColorEffect": "0",
                "ContrastAmount": "0.65",
                "ContrastEffect": "1",
                "IntensityAmount": "0.1",
                "IntensityEffect": "2",
            },
        ),
        _section(
            "ColorEffects:Inactive",
            {
                "ChangeSelectionColor": "true",
                "Color": rgb(t["border"]),
                "ColorAmount": "0.025",
                "ColorEffect": "2",
                "ContrastAmount": "0.1",
                "ContrastEffect": "2",
                "Enable": "false",
                "IntensityAmount": "0",
                "IntensityEffect": "0",
            },
        ),
    ]
    for group, (normal, alternate) in groups.items():
        sections.append(
            _section(group, {**fg, "BackgroundNormal": rgb(normal), "BackgroundAlternate": rgb(alternate)})
        )
    # Selection uses dark text on the teal accent for WCAG-friendly contrast.
    sections.append(
        _section(
            "Colors:Selection",
            {
                **fg,
                "BackgroundNormal": rgb(t["accent-primary"]),
                "BackgroundAlternate": rgb(t["background-secondary"]),
                "ForegroundActive": rgb(t["background-primary"]),
                "ForegroundInactive": rgb(t["surface-elevated"]),
                "ForegroundLink": rgb(t["background-secondary"]),
                "ForegroundNormal": rgb(t["background-primary"]),
            },
        )
    )
    sections.append(
        "[General]\nColorScheme=Nexus\nName=Nexus\nshadeSortColumn=true\n"
        f"AccentColor={rgb(t['accent-primary'])}\n"
    )
    sections.append("[KDE]\ncontrast=4\n")
    sections.append(
        _section(
            "WM",
            {
                "activeBackground": rgb(t["surface"]),
                "activeBlend": rgb(t["text-primary"]),
                "activeForeground": rgb(t["text-primary"]),
                "inactiveBackground": rgb(t["background-primary"]),
                "inactiveBlend": rgb(t["text-secondary"]),
                "inactiveForeground": rgb(t["text-secondary"]),
            },
        )
    )
    return HEADER + "\n" + "\n".join(sections)


# ANSI palette: (normal, intense). Teal/copper come from tokens; the rest are tuned to sit on #0B171B.
ANSI = {
    "Color0": ("surface", "#29434A"),
    "Color1": ("negative", "#EB786E"),
    "Color2": ("positive", "#64D696"),
    "Color3": ("warning", "#ECBE69"),
    "Color4": ("#4F9CD6", "#78B8E8"),
    "Color5": ("#B478C8", "#CD9BE1"),
    "Color6": ("accent-primary", "accent-primary-hover"),
    "Color7": ("text-secondary", "text-primary"),
}


def render_konsole(t: dict[str, str]) -> str:
    def resolve(ref: str) -> str:
        return rgb(ref if ref.startswith("#") else t[ref])

    parts = [
        f"[Background]\nColor={rgb(t['background-primary'])}\n",
        f"[BackgroundIntense]\nColor={rgb(t['surface'])}\n",
        f"[Foreground]\nColor={rgb(t['text-primary'])}\n",
        f"[ForegroundIntense]\nColor={rgb(t['text-primary'])}\n",
    ]
    for name, (normal, intense) in ANSI.items():
        parts.append(f"[{name}]\nColor={resolve(normal)}\n")
        parts.append(f"[{name}Intense]\nColor={resolve(intense)}\n")
    parts.append("[General]\nDescription=Nexus\nOpacity=0.96\nBlur=true\n")
    return HEADER + "\n" + "\n".join(parts)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if generated files are out of date")
    args = parser.parse_args(argv)

    tokens = load_tokens()
    outputs = {COLORS_OUT: render_color_scheme(tokens), KONSOLE_OUT: render_konsole(tokens)}
    stale = []
    for path, content in outputs.items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == content:
            continue
        if args.check:
            stale.append(path)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
            print(f"wrote {path.relative_to(REPO_ROOT)}")
    if stale:
        for path in stale:
            print(f"out of date: {path.relative_to(REPO_ROOT)}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
