"""Render validated routes to NGINX server blocks.

Only values that passed :mod:`nexus_core.gateway.model` validation are interpolated,
so no user input can inject NGINX directives.
"""

from __future__ import annotations

import ipaddress
from pathlib import Path

from nexus_core.gateway.model import Route

HEADER = "# Generated by NexusOS Gateway from routes/{id}.yaml -- DO NOT EDIT (changes are overwritten).\n"

ACCESS_RULES = {
    "localhost": ["allow 127.0.0.0/8;", "allow ::1;", "deny all;"],
    "lan": [
        "allow 127.0.0.0/8;",
        "allow ::1;",
        "allow 10.0.0.0/8;",
        "allow 172.16.0.0/12;",
        "allow 192.168.0.0/16;",
        "allow fc00::/7;",
        "allow fe80::/10;",
        "deny all;",
    ],
    "public": [],
}


def _backend_url(route: Route) -> str:
    host = route.backend_host
    try:
        if isinstance(ipaddress.ip_address(host), ipaddress.IPv6Address):
            host = f"[{host}]"
    except ValueError:
        pass
    return f"{route.backend_scheme}://{host}:{route.backend_port}"


def cert_paths(route: Route, gateway_dir: Path) -> tuple[Path, Path]:
    if route.tls == "letsencrypt":
        live = Path("/etc/letsencrypt/live") / route.hostname
        return live / "fullchain.pem", live / "privkey.pem"
    base = gateway_dir / "certificates" / route.cert_name
    return base / "fullchain.pem", base / "privkey.pem"


def _location(route: Route, indent: str = "    ") -> list[str]:
    lines = [f"location {route.path_prefix} {{"]
    lines += [f"    {rule}" for rule in ACCESS_RULES[route.access]]
    lines += [
        f"    proxy_pass {_backend_url(route)};",
        "    proxy_http_version 1.1;",
        "    proxy_set_header Host $host;",
        "    proxy_set_header X-Real-IP $remote_addr;",
        "    proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;",
        "    proxy_set_header X-Forwarded-Proto $scheme;",
        "    proxy_read_timeout 300s;",
    ]
    if route.websocket:
        lines += [
            "    proxy_set_header Upgrade $http_upgrade;",
            "    proxy_set_header Connection $nexusos_connection_upgrade;",
        ]
    if route.backend_scheme == "https":
        lines += ["    proxy_ssl_server_name on;"]
    lines.append("}")
    return [indent + ln for ln in lines]


def ipv6_available(proc: Path = Path("/proc/net/if_inet6")) -> bool:
    """Only emit IPv6 listeners when the host has IPv6 (otherwise nginx -t fails)."""
    try:
        return bool(proc.read_text().strip())
    except OSError:
        return False


def render_route(route: Route, gateway_dir: Path, ipv6: bool = True) -> str:
    acme = [
        "    location ^~ /.well-known/acme-challenge/ {",
        f"        root {gateway_dir / 'acme'};",
        "        default_type text/plain;",
        "    }",
    ]
    out = [HEADER.format(id=route.id)]
    if route.description:
        out.append(f"# {route.description}\n")
    http = [
        "server {",
        "    listen 80;",
        *(["    listen [::]:80;"] if ipv6 else []),
        f"    server_name {route.hostname};",
        f"    client_max_body_size {route.max_body_size};",
    ]
    if route.tls == "letsencrypt":
        http += acme
    if route.tls != "none" and route.redirect_http:
        http += ["    location / {", "        return 301 https://$host$request_uri;", "    }"]
    else:
        http += _location(route)
    http.append("}")
    out.append("\n".join(http) + "\n")
    if route.tls != "none":
        cert, key = cert_paths(route, gateway_dir)
        https = [
            "server {",
            "    listen 443 ssl;",
            *(["    listen [::]:443 ssl;"] if ipv6 else []),
            "    http2 on;",
            f"    server_name {route.hostname};",
            f"    ssl_certificate {cert};",
            f"    ssl_certificate_key {key};",
            "    ssl_protocols TLSv1.2 TLSv1.3;",
            "    ssl_session_cache shared:nexusos_gw:10m;",
            f"    client_max_body_size {route.max_body_size};",
            '    add_header X-Content-Type-Options "nosniff" always;',
        ]
        if route.access == "public" and route.tls == "letsencrypt":
            https.append('    add_header Strict-Transport-Security "max-age=31536000" always;')
        https += _location(route)
        https.append("}")
        out.append("\n" + "\n".join(https) + "\n")
    return "".join(out)


def render_all(routes: list[Route], gateway_dir: Path, ipv6: bool | None = None) -> dict[str, str]:
    ipv6 = ipv6_available() if ipv6 is None else ipv6
    return {f"{r.id}.conf": render_route(r, gateway_dir, ipv6) for r in routes if r.enabled and r.approved}


# Installed once as /etc/nginx/conf.d/nexusos-gateway.conf by nexusos-gateway.
NGINX_INCLUDE = """# NexusOS Gateway -- loads generated routes. Managed by the nexusos-gateway package.
map $http_upgrade $nexusos_connection_upgrade {
    default upgrade;
    ''      close;
}
include /etc/nexusos/gateway/generated/*.conf;
"""
