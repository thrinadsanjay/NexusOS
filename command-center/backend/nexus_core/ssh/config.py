"""Generate an OpenSSH client configuration from profiles.

The file lives in $XDG_RUNTIME_DIR/nexusos/ssh_config (mode 0600) and is passed with
``ssh -F``; the user's ~/.ssh/config is included first so existing settings keep working.
It never contains secrets: passwords come from the Secret Service via SSH_ASKPASS.
"""

from __future__ import annotations

import os
from pathlib import Path

from nexus_core import paths
from nexus_core.ssh.profiles import SSHProfile


def render(profiles: list[SSHProfile], user_config: Path | None = None) -> str:
    by_id = {p.id: p for p in profiles}
    user_config = user_config or Path.home() / ".ssh" / "config"
    lines = ["# Generated by NexusOS Command Center -- do not edit; regenerated on every connection.", ""]
    for p in profiles:
        lines.append(f"Host {p.alias}")
        lines += [f"    HostName {p.host}", f"    Port {p.port}", f"    User {p.user}"]
        if p.auth == "key" and p.key_path:
            lines += [f'    IdentityFile "{Path(p.key_path).expanduser()}"', "    IdentitiesOnly yes"]
        if p.auth == "password":
            lines += ["    PreferredAuthentications password,keyboard-interactive", "    PubkeyAuthentication no"]
        if p.jump_profile_id and p.jump_profile_id in by_id:
            lines.append(f"    ProxyJump {by_id[p.jump_profile_id].alias}")
        lines.append(f"    ForwardAgent {'yes' if p.agent_forwarding else 'no'}")
        for fwd in p.forwards:
            key, value = fwd.ssh_option()
            lines.append(f"    {key} {value}")
        options = {
            "StrictHostKeyChecking": "yes" if p.auth == "password" else "ask",
            "ServerAliveInterval": "30",
            **p.options,
        }
        if p.auth == "password":
            # Askpass is forced for passwords, so it must never answer host-key questions.
            options["StrictHostKeyChecking"] = "yes"
        for key, value in options.items():
            lines.append(f"    {key} {value}")
        lines.append("")
    if user_config.exists():
        lines += [f'Include "{user_config}"', ""]
    return "\n".join(lines)


def write(profiles: list[SSHProfile]) -> Path:
    target = paths.runtime_dir() / "ssh_config"
    fd = os.open(target, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w") as handle:
        handle.write(render(profiles))
    return target
